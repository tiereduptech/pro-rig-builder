//
//  One-shot transform: src/data/parts.js (one giant PARTS array) →
//    src/data/parts/<cat>.js  (one file per category, default-export array)
//    src/data/parts.js        (re-written as static-import barrel of all cats)
//
//  Goal: let Vite split the 4.26 MB parts-data chunk into per-category
//  chunks so category pages only download what they need.
//
//  Server-side compatibility: prerender.cjs and scripts/url-slugs.cjs call
//  loadParts() which dynamic-imports parts.js. The barrel still exports
//  the full concatenated PARTS array, so server-side behavior is identical.
//
//  Idempotent: safe to re-run after parts.js updates. Asserts that the
//  product count after the split matches the count before.
// =============================================================================

const fs = require('fs');
const path = require('path');

const ROOT       = path.resolve(__dirname, '..');
const PARTS_JS   = path.join(ROOT, 'src/data/parts.js');
const PARTS_DIR  = path.join(ROOT, 'src/data/parts');

// CAT_SLUG is the source of truth for which categories get a filename.
// Anything not listed falls into _misc.js so we never silently drop products.
const { CAT_SLUG } = require('./url-slugs.cjs');

// Convert "CPUCooler" → "cpu-cooler" — matches CAT_SLUG values, used as filename.
const catToFile = (catKey) => (CAT_SLUG[catKey] || 'misc');

(async () => {
  // Use the existing async loader so we share its parsing path with prerender.
  // file:// + cache-buster handles Windows paths and stale module cache.
  const url = 'file:///' + PARTS_JS.replace(/\\/g, '/') + '?t=' + Date.now();
  const mod = await import(url);
  const PARTS = mod.PARTS || mod.default || [];

  const beforeCount = PARTS.length;
  if (!beforeCount) {
    console.error('ERROR: parts.js returned 0 products. Aborting.');
    process.exit(1);
  }

  // Group by category. Anything with an unknown category goes into _misc so
  // it still reaches the client — server-side filtering already drops
  // non-indexable products, but we want zero data loss in the split.
  //
  // First-seen order is preserved so the barrel re-concats in the same
  // order PARTS originally appeared (CPUs first, etc.) — anything in the
  // app that surfaces "first N products" stays stable.
  const byCat = new Map();
  for (const p of PARTS) {
    const file = catToFile(p.c);
    if (!byCat.has(file)) byCat.set(file, []);
    byCat.get(file).push(p);
  }

  // Write per-category files.
  fs.mkdirSync(PARTS_DIR, { recursive: true });
  // Clean any stale per-cat files before writing fresh ones, so a category
  // removed upstream doesn't linger as a dead chunk.
  for (const f of fs.readdirSync(PARTS_DIR)) {
    if (f.endsWith('.js')) fs.unlinkSync(path.join(PARTS_DIR, f));
  }

  // Two orderings:
  //   fileNamesAlpha — alphabetical, used for the on-disk filename list
  //   so per-file hashes only churn when that file's contents change.
  //   fileNamesSeen  — first-seen-in-original-PARTS order, used for the
  //   barrel concat so PARTS order is preserved.
  const fileNamesAlpha = [...byCat.keys()].sort();
  const fileNamesSeen  = [...byCat.keys()];
  let perFileTotal = 0;
  for (const file of fileNamesAlpha) {
    const arr = byCat.get(file);
    perFileTotal += arr.length;
    const body = `// Auto-generated by scripts/split-parts-by-cat.cjs. Do not edit by hand.\n` +
                 `// One file per category so Vite can split parts data into per-category chunks.\n` +
                 `export default ${JSON.stringify(arr, null, 2)};\n`;
    fs.writeFileSync(path.join(PARTS_DIR, file + '.js'), body);
  }

  if (perFileTotal !== beforeCount) {
    console.error(`ERROR: per-file total ${perFileTotal} != original ${beforeCount}`);
    process.exit(1);
  }

  // Re-write src/data/parts.js as a barrel. Static imports keep it usable
  // both server-side (prerender, sitemap) and as a fallback path for any
  // tooling that grabs the full catalog synchronously.
  // Imports are alpha-ordered so the source diff is stable across runs.
  // Concat uses first-seen order so the resulting PARTS array preserves
  // the original product order (CPUs first, etc.).
  const fileIdx = new Map(fileNamesAlpha.map((f, i) => [f, i]));
  const importLines  = fileNamesAlpha.map((f, i) => `import _${i} from './parts/${f}.js';`).join('\n');
  const concatExpr   = fileNamesSeen.map(f => `..._${fileIdx.get(f)}`).join(', ');
  const barrel =
    `// Auto-generated by scripts/split-parts-by-cat.cjs. Do not edit by hand.\n` +
    `//\n` +
    `// Server-side barrel: prerender.cjs and scripts/url-slugs.cjs import this\n` +
    `// to get the full PARTS array. The frontend uses src/data/parts-frontend.js,\n` +
    `// which dynamic-imports per-category modules so they end up in separate\n` +
    `// Vite chunks.\n` +
    `${importLines}\n\n` +
    `export const PARTS = [${concatExpr}];\n` +
    `export default PARTS;\n`;
  fs.writeFileSync(PARTS_JS, barrel);

  // Sanity: re-import via fresh cache-buster, confirm count.
  const verifyUrl = 'file:///' + PARTS_JS.replace(/\\/g, '/') + '?t=' + Date.now();
  const verifyMod = await import(verifyUrl);
  const afterCount = (verifyMod.PARTS || verifyMod.default || []).length;
  if (afterCount !== beforeCount) {
    console.error(`ERROR: after split, parts.js exports ${afterCount} != ${beforeCount}`);
    process.exit(1);
  }

  console.log(`SPLIT OK: ${beforeCount} products across ${fileNamesAlpha.length} files`);
  console.log(`  ${PARTS_DIR}/<cat>.js`);
  console.log(`  ${PARTS_JS}  (barrel, re-exports concat)`);
})().catch(e => {
  console.error('FAILED:', e);
  process.exit(1);
});
