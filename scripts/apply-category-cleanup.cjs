// One-shot: apply the approved category-accuracy cleanup.
//  - DELETE 83 accessory / wrong-type rows (Section A of the report)
//  - RECAT 8 misfiled rows to their correct category (Section B)
//  - RECAT 36 external/portable drives Storage -> ExternalStorage
// Writes per-cat files + barrel using the same grouping split-parts-by-cat.cjs
// uses; run the official split afterwards as an independent re-verification.
const fs = require('fs');
const path = require('path');
const { CAT_SLUG } = require('./url-slugs.cjs');

const ROOT      = path.resolve(__dirname, '..');
const PARTS_JS  = path.join(ROOT, 'src/data/parts.js');
const PARTS_DIR = path.join(ROOT, 'src/data/parts');

const DELETE = new Set([
  // CPUCooler
  101241,101389,101910, 100374,101262,101410,101921, 100960, 100972,100975,
  // Storage
  101267,101415,101926,101271,101280,101419,101428,
  101269,101417,101928,101288,101436,101934,
  100823,101276,101277,101281,101282,101283,101284,101285,101286,
  101424,101425,101429,101430,101431,101432,101433,101434,
  // PSU
  101207,101355,101887, 101209,101357,101889, 100571,100573,
  // CaseFan
  101138,101141,
  // Microphone
  101748,101749,101766,101768,101778,101780,101825,
  101751,101754,101757,101759,101761,101779,101830,101833,101834,101835,
  101760,101783,101832,101829, 101819,
  // Headset
  101172,101320,101673,101669, 101174,101322,101675,101647, 101645,
  // CPU
  // NOTE: 100621/100622/100623 (Acer Aspire prebuilt desktops) intentionally
  // NOT deleted — real sellable products with affiliate value; kept as-is in CPU
  // (no Desktop/Prebuilt category exists yet). See owner instruction 2026-07-08.
  100636,
  // Motherboard
  20352,
]);

const RECAT = new Map();
for (const id of [100375,101239,101387,100959,100971]) RECAT.set(id, 'CaseFan');
for (const id of [101240,101388,101909]) RECAT.set(id, 'Headset');
for (const id of [50040,50057,50063,50070,50073,50114,50115,50119,50127,50198,50249,
  50271,50275,50276,50540,50541,50542,50543,100820,100830,100832,100834,100836,100847,
  100858,100869,100870,101268,101287,101289,101416,101435,101437,101927,101933,101935])
  RECAT.set(id, 'ExternalStorage');

(async () => {
  const url = 'file:///' + PARTS_JS.replace(/\\/g, '/') + '?t=' + Date.now();
  const { PARTS } = await import(url);
  const before = PARTS.length;

  // Verify every targeted id exists exactly once before touching anything.
  const idCount = new Map();
  for (const p of PARTS) idCount.set(p.id, (idCount.get(p.id) || 0) + 1);
  const targets = [...DELETE, ...RECAT.keys()];
  const bad = targets.filter(id => (idCount.get(id) || 0) !== 1);
  if (bad.length) { console.error('ABORT: targeted ids missing/duplicated:', bad.join(',')); process.exit(1); }

  const mutated = [];
  let del = 0, rec = 0;
  for (const p of PARTS) {
    if (DELETE.has(p.id)) { del++; continue; }
    if (RECAT.has(p.id)) { p.c = RECAT.get(p.id); rec++; }
    mutated.push(p);
  }
  const after = mutated.length;
  if (after !== before - DELETE.size) {
    console.error(`ABORT: expected ${before - DELETE.size} rows, got ${after}`); process.exit(1);
  }

  // Group + write exactly like split-parts-by-cat.cjs so the official split
  // is a pure idempotent re-verification.
  const byCat = new Map();
  for (const p of mutated) {
    const file = CAT_SLUG[p.c] || 'misc';
    if (!byCat.has(file)) byCat.set(file, []);
    byCat.get(file).push(p);
  }
  for (const f of fs.readdirSync(PARTS_DIR)) if (f.endsWith('.js')) fs.unlinkSync(path.join(PARTS_DIR, f));

  const alpha = [...byCat.keys()].sort();
  const seen  = [...byCat.keys()];
  for (const file of alpha) {
    const body = `// Auto-generated by scripts/split-parts-by-cat.cjs. Do not edit by hand.\n` +
                 `// One file per category so Vite can split parts data into per-category chunks.\n` +
                 `export default ${JSON.stringify(byCat.get(file), null, 2)};\n`;
    fs.writeFileSync(path.join(PARTS_DIR, file + '.js'), body);
  }
  const idx = new Map(alpha.map((f, i) => [f, i]));
  const importLines = alpha.map((f, i) => `import _${i} from './parts/${f}.js';`).join('\n');
  const concatExpr  = seen.map(f => `..._${idx.get(f)}`).join(', ');
  const barrel =
    `// Auto-generated by scripts/split-parts-by-cat.cjs. Do not edit by hand.\n//\n` +
    `// Server-side barrel: prerender.cjs and scripts/url-slugs.cjs import this\n` +
    `// to get the full PARTS array. The frontend uses src/data/parts-frontend.js,\n` +
    `// which dynamic-imports per-category modules so they end up in separate\n` +
    `// Vite chunks.\n` +
    `${importLines}\n\n` +
    `export const PARTS = [${concatExpr}];\n` +
    `export default PARTS;\n`;
  fs.writeFileSync(PARTS_JS, barrel);

  console.log(`APPLIED: deleted ${del}, recategorized ${rec}. ${before} -> ${after} rows.`);
})().catch(e => { console.error('FAILED:', e); process.exit(1); });
